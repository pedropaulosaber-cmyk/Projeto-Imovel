/**
 * Vocabulário semente dos 5 idiomas iniciais.
 *
 * ## Critério de seleção
 *
 * As palavras seguem **frequência de uso real**, não ordem temática arbitrária.
 * As 1.000 palavras mais frequentes de uma língua cobrem cerca de 80% de um
 * texto corrente; as 3.000 primeiras cobrem ~95% da fala cotidiana. Ensinar na
 * ordem de frequência é a alavanca mais eficiente que existe em aquisição de
 * vocabulário — e é onde apps organizados por "temas" (cores, animais, frutas)
 * desperdiçam meses do usuário.
 *
 * Cada verbete tem exemplo em contexto, porque palavra isolada não se fixa: a
 * memória guarda a frase, não o par de tradução.
 *
 * Este arquivo é a **semente offline** embutida no binário — o que garante que
 * um usuário sem internet consiga começar a estudar no primeiro minuto. O
 * corpus completo (3.000+ termos por idioma, com áudio) chega pelos pacotes de
 * download.
 */

