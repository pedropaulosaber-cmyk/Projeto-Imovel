const LEVEL_VOCABULARY: Partial<Record<LanguageCode, LevelMap>> = {
  en: EN,
  es: ES,
  fr: FR,
  it: IT,
  de: DE,
};

/**
 * Verbetes de um idioma num nível. Devolve lista vazia (nunca `undefined`)
 * para que quem consome não precise checar — conteúdo ausente é uma lista
 * sem itens, não um caso de erro.
 */
export function levelVocabulary(language: LanguageCode, level: CefrLevel): LevelEntry[] {
  return LEVEL_VOCABULARY[language]?.[level] ?? [];
}

/** Todos os níveis que têm conteúdo próprio num idioma. */
export function levelsWithContent(language: LanguageCode): CefrLevel[] {
  const map = LEVEL_VOCABULARY[language];
  if (!map) return [];
  return LEVELED_CEFR.filter((level) => (map[level]?.length ?? 0) > 0);
}

export { LEVEL_VOCABULARY };
