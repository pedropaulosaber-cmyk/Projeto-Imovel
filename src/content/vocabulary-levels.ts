/**
 * Vocabulário por nível CEFR — idiomas de escrita latina
 * =======================================================
 *
 * ## Por que A1 não está aqui
 *
 * A1 vem da lista de frequência em `vocabulary.ts`, e isso é uma decisão
 * pedagógica, não uma economia. No início, **frequência é o único critério que
 * importa**: as 500 palavras mais comuns cobrem a maior parte de qualquer
 * conversa banal, e são justamente artigos, verbos irregulares e preposições —
 * o esqueleto da língua. Organizar A1 por tema ("cores", "frutas") é o erro
 * clássico que faz o aluno saber dizer "abacaxi" antes de saber dizer "ainda".
 *
 * ## Por que A2 em diante está aqui
 *
 * Passado o núcleo de alta frequência, frequência para de discriminar: as
 * palavras 2.000 a 8.000 têm frequências parecidas entre si e o que muda é o
 * **domínio de uso**. A partir daí o corte certo é por situação e registro —
 * e é isso que cada nível abaixo representa:
 *
 *  - **A2** — sobrevivência ampliada: rotina, cidade, saúde, compras.
 *  - **B1** — opinião e narrativa: contar o que aconteceu, discordar, explicar.
 *  - **B2** — abstração e nuance: causa, consequência, hipótese, crítica.
 *  - **C1** — registro acadêmico e profissional, conectivos de argumentação.
 *  - **C2** — precisão idiomática, conotação, palavras que um nativo culto usa.
 *
 * ## A regra que este arquivo precisa cumprir
 *
 * **Nenhum termo se repete** — nem dentro de um nível, nem entre níveis, nem
 * contra a lista de A1. É o que garante que o aluno de C1 não receba de volta
 * a mesma pergunta que respondeu no A2. Há teste automatizado para isso em
 * `__tests__/vocabulary-levels.test.ts`; se você adicionar uma palavra que já
 * existe em outro nível, a suíte quebra de propósito.
 */

